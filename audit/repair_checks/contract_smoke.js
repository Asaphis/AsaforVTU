const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..', '..');
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const frontendAuth = read('web/frontend/src/lib/auth.ts');
const services = read('web/frontend/src/lib/services.ts');
const notifications = read('web/frontend/src/contexts/NotificationContext.tsx');
const layout = read('web/frontend/src/app/layout.tsx');
const pin = read('web/frontend/src/components/dashboard/TransactionPinModal.tsx');
const vtu = read('backend/src/routes/vtuRoutes.js');
const authRoutes = read('backend/src/routes/authRoutes.js');
const adminProxy = read('web/admin/server/routes.js');
const app = read('backend/src/app.js');

assert.match(frontendAuth, /Registration intentionally does not create an authenticated browser session/);
assert.match(frontendAuth, /AbortSignal\.timeout\(3000\)/);
assert.match(frontendAuth, /resend-verification/);
assert.match(frontendAuth, /verify-pin/);
assert.doesNotMatch(services, /\/api\/vtu\/(airtime|data)/);
assert.match(services, /\/api\/vtu\/purchase/);
assert.match(read('web/frontend/src/app/dashboard/services/airtime/page.tsx'), /transactionPin/);
assert.match(services, /apiRequest\('\/api\/services/);
assert.match(notifications, /\/api\/notifications\?unreadOnly=true/);
assert.match(notifications, /read-all/);
assert.ok(layout.indexOf('<AuthProvider>') < layout.indexOf('<NotificationProvider>'));
assert.match(pin, /verifyPin\(pin\)/);
assert.match(vtu, /'exam-pins'/);
assert.match(vtu, /verifyPin/);
assert.match(authRoutes, /resend-verification/);
assert.match(adminProxy, /\/api\/admin\/services/);
assert.match(adminProxy, /\/api\/admin\/plans/);
assert.match(adminProxy, /\/api\/admin\/finance\/analytics/);
assert.match(app, /app\.get\('\/api\/health'/);
console.log('contract smoke checks passed');
